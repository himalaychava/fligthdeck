/**
 * Health Check Template Generator
 * 
 * Generates Excel template files for Health Check Tool to fill with actual health data.
 * Template includes client information and empty columns for health check results.
 */

import XLSX from 'xlsx';
import fs from 'fs';
import path from 'path';
import { HEALTH_CHECK_SHARED_CONFIG, getRequestFilePath } from '@/config/healthCheckShared';

export interface HealthCheckTemplateRequest {
  clientId: string;
  clientName: string;
  timestamp?: string;
}

export interface HealthCheckTemplateResult {
  success: boolean;
  filePath?: string;
  fileName?: string;
  error?: string;
}

/**
 * Generate a health check template Excel file for a client
 * 
 * The template includes:
 * - Client ID and Client Name (pre-filled)
 * - Empty columns for: Product, Main KPI, Sub KPI, Status, Score, Last Updated
 * 
 * Health Check Tool will fill in the empty columns with actual health data.
 */
export function generateHealthCheckTemplate(
  request: HealthCheckTemplateRequest
): HealthCheckTemplateResult {
  try {
    const { clientId, clientName, timestamp } = request;
    
    // Generate timestamp if not provided (format: YYYYMMDD_HHMMSS)
    const ts = timestamp || (() => {
      const now = new Date();
      const date = now.toISOString().split('T')[0].replace(/-/g, ''); // YYYYMMDD
      const time = now.toTimeString().split(' ')[0].replace(/:/g, ''); // HHMMSS
      return `${date}_${time}`;
    })();
    
    // Get file path
    const filePath = getRequestFilePath(clientId, ts);
    const fileName = path.basename(filePath);
    
    // Ensure requests directory exists
    if (!fs.existsSync(HEALTH_CHECK_SHARED_CONFIG.requestsDir)) {
      fs.mkdirSync(HEALTH_CHECK_SHARED_CONFIG.requestsDir, { recursive: true });
    }
    
    // Note: We keep all request files with different timestamps for history tracking
    // Each click creates a new file instead of overwriting the previous one
    
    // Create template data with one row showing the structure
    const templateData = [
      {
        'Client ID': clientId,
        'Client Name': clientName,
        'Product': '', // Empty - Health Check Tool fills this
        'Main KPI': '', // Empty - Health Check Tool fills this
        'Sub KPI': '', // Empty - Health Check Tool fills this
        'Status': '', // Empty - Health Check Tool fills this (Excellent/Good/Warning/Critical)
        'Score': '', // Empty - Health Check Tool fills this (10/7/5/3)
        'Last Updated': '' // Empty - Health Check Tool fills this
      }
    ];
    
    // Create workbook
    const workbook = XLSX.utils.book_new();
    const worksheet = XLSX.utils.json_to_sheet(templateData);
    
    // Set column widths for better readability
    worksheet['!cols'] = [
      { wch: 25 }, // Client ID
      { wch: 30 }, // Client Name
      { wch: 25 }, // Product
      { wch: 25 }, // Main KPI
      { wch: 35 }, // Sub KPI
      { wch: 15 }, // Status
      { wch: 10 }, // Score
      { wch: 15 }  // Last Updated
    ];
    
    // Add worksheet to workbook
    XLSX.utils.book_append_sheet(workbook, worksheet, 'Health Check Template');
    
    // Add instructions sheet
    const instructionsData = [
      { Instruction: 'This is a Health Check Template generated by Control Plane' },
      { Instruction: '' },
      { Instruction: 'Client Information:' },
      { Instruction: `  Client ID: ${clientId}` },
      { Instruction: `  Client Name: ${clientName}` },
      { Instruction: `  Generated: ${new Date().toISOString()}` },
      { Instruction: '' },
      { Instruction: 'Instructions for Health Check Tool:' },
      { Instruction: '1. Read the Client ID and Client Name from the template' },
      { Instruction: '2. For each product this client has, add rows with:' },
      { Instruction: '   - Product name (e.g., IBM Db2, IBM MQ, Red Hat OpenShift)' },
      { Instruction: '   - Main KPI (e.g., Risk Analysis, Product Stabilty, Product Performance)' },
      { Instruction: '   - Sub KPI (e.g., Database Version, CPU Load average)' },
      { Instruction: '   - Status (Excellent, Good, Warning, or Critical)' },
      { Instruction: '   - Score (10 for Excellent, 7 for Good, 5 for Warning, 3 for Critical)' },
      { Instruction: '   - Last Updated (current date in YYYY-MM-DD format)' },
      { Instruction: '3. Save the completed file to the "completed" folder with "-completed" suffix' },
      { Instruction: '' },
      { Instruction: 'Example completed filename:' },
      { Instruction: `  ${fileName.replace('.xlsx', '-completed.xlsx')}` }
    ];
    
    const instructionsSheet = XLSX.utils.json_to_sheet(instructionsData);
    instructionsSheet['!cols'] = [{ wch: 80 }];
    XLSX.utils.book_append_sheet(workbook, instructionsSheet, 'Instructions');
    
    // Write file
    XLSX.writeFile(workbook, filePath);
    
    console.log(`✅ Health Check template generated: ${fileName}`);
    console.log(`   Path: ${filePath}`);
    console.log(`   Client: ${clientName} (${clientId})`);
    
    return {
      success: true,
      filePath,
      fileName
    };
    
  } catch (error) {
    console.error('Error generating health check template:', error);
    return {
      success: false,
      error: error instanceof Error ? error.message : 'Unknown error'
    };
  }
}

/**
 * Check if a completed health check file exists for a client
 */
export function checkCompletedFileExists(clientId: string): {
  exists: boolean;
  filePath?: string;
  fileName?: string;
} {
  try {
    if (!fs.existsSync(HEALTH_CHECK_SHARED_CONFIG.completedDir)) {
      return { exists: false };
    }
    
    // Find the most recent completed file for this client
    const files = fs.readdirSync(HEALTH_CHECK_SHARED_CONFIG.completedDir)
      .filter(f => {
        return f.startsWith(`health-check-completed-${clientId}-`) &&
               f.endsWith('.xlsx') &&
               !f.startsWith('~$');
      })
      .sort()
      .reverse(); // Most recent first
    
    if (files.length > 0) {
      const fileName = files[0];
      const filePath = path.join(HEALTH_CHECK_SHARED_CONFIG.completedDir, fileName);
      return {
        exists: true,
        filePath,
        fileName
      };
    }
    
    return { exists: false };
    
  } catch (error) {
    console.error('Error checking completed file:', error);
    return { exists: false };
  }
}

